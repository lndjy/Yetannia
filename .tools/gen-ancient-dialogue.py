#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generate Yetannia's Ancient-dialogue C# data file from the parsed draft plus its English column.

Input : .tools/dialogue/parsed.json          (produced by .tools/parse-dialogue.py)
        .tools/dialogue/translated-en.json    (hand-authored English column, npc -> slot -> lines)
Output: Yetannia/Code/Ancients/YetanniaAncientDialogueData.g.cs

Run:  python .tools/parse-dialogue.py && python .tools/gen-ancient-dialogue.py

Why generate C# rather than ship a localization JSON:

  * The mod already localizes everything else in code (`Loc.Pick` / `ILocalizationProvider`),
    and its gameplay strings must survive a mid-session language switch -- `LocManager.SetLanguage`
    rebuilds every LocTable from disk, so anything not re-injected afterwards is wiped. Injecting
    from a static C# table on `LocManager.GetTable` is the pattern this mod already uses three
    times (KeywordLocPatch, SettingsLocPatch, ModelLocReloadPatch).
  * The dialogue keys are this mod's own namespace (`YETANNIA-TALK.*`), so the text does not have
    to be threaded through vanilla's derived-key naming at all.

BOTH LANGUAGES LIVE IN THE GENERATED TABLE. `Text` is the user's Chinese (the authority, never
reworded), `TextEn` is the English from translated-en.json. `YetanniaAncientDialoguePlan.LocEntries`
picks between them at runtime: `true` -> English for `eng`, `false` -> Chinese for every other
language, so Chinese stays the default fallback. The translation file records the Chinese that each
English line translates; this script refuses to generate when the two disagree, so editing the draft
cannot silently leave the English column describing different lines.

Escaping: C# string literals are emitted with `\\`, `\"` and `\n` escaped. Any line containing a
character that cannot be represented safely is reported and the script exits non-zero.
"""

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PARSED = os.path.join(HERE, "dialogue", "parsed.json")
TRANSLATED = os.path.join(HERE, "dialogue", "translated-en.json")
OUT = os.path.join(ROOT, "Yetannia", "Code", "Ancients", "YetanniaAncientDialogueData.g.cs")

# Anything in these blocks means the "English" column still carries Chinese. Used to reject a
# half-translated line rather than let it ship.
CJK = re.compile(r"[\u3000-\u303F\u3400-\u4DBF\u4E00-\u9FFF\uF900-\uFAFF\uFF00-\uFFEF]")

# docx NPC -> the Ancient model id entry the game uses for `base.Id.Entry`, i.e. what
# `AncientDialogueSet.PopulateLocKeys(ancientEntry)` receives. Measured from the vanilla
# `ancients` loc table (keys are `<ENTRY>.talk...`) and from the model classes.
#
# The vanilla class each entry belongs to is listed so the patch targets are auditable.
ANCIENTS = [
    ("涅奥", "NEOW", "MegaCrit.Sts2.Core.Models.Events.Neow"),
    ("欧洛巴斯", "OROBAS", "MegaCrit.Sts2.Core.Models.Events.Orobas"),
    ("佩尔", "PAEL", "MegaCrit.Sts2.Core.Models.Events.Pael"),
    ("瓦库", "VAKUU", "MegaCrit.Sts2.Core.Models.Events.Vakuu"),
    ("坦克斯", "TANX", "MegaCrit.Sts2.Core.Models.Events.Tanx"),
    ("特兹卡塔拉", "TEZCATARA", "MegaCrit.Sts2.Core.Models.Events.Tezcatara"),
    ("诺奴佩普", "NONUPEIPE", "MegaCrit.Sts2.Core.Models.Events.Nonupeipe"),
    ("达弗", "DARV", "MegaCrit.Sts2.Core.Models.Events.Darv"),
    ("建筑师", "THE_ARCHITECT", "(TheArchitect: has its own DialogueSet, not an AncientEventModel)"),
]

# The section slots the plan understands, in dialogue-index order. Must stay in sync with
# YetanniaAncientDialoguePlan.Slots in the hand-written C# file.
SLOT_ORDER = [
    "first",
    "first@branch1",
    "repeat1",
    "repeat2",
    "late",
    "late@branch1",
    "late@branch2",
    "generic1",
    "generic2",
]

HEADER = '''// <auto-generated>
//     Generated by .tools/gen-ancient-dialogue.py from the user's .docx drafts in
//     .tools/dialogue/ (via .tools/dialogue/parsed.json). DO NOT EDIT BY HAND.
//
//     Re-generate with:
//         python .tools/parse-dialogue.py && python .tools/gen-ancient-dialogue.py
//     The English column is not derived from the .docx: it is read from
//     .tools/dialogue/translated-en.json, which is hand-authored next to the .docx drafts.
//
//     Each DraftSection.Slot matches one heading in the user's draft:
//         generic1/generic2 -> 通用1 / 通用2
//         first            -> 初次见面           first@branch1 -> 分支1
//         repeat1          -> 重复拜访 / 重复拜访1
//         repeat2          -> 重复拜访2
//         late             -> 第三次及其以后
//         late@branch1     -> 第三次及其以后分支1
//         late@branch2     -> 第三次及其以后分支2
//         architect-main   -> the Architect's one flat, heading-less conversation
//
//     The TEXT IS THE USER'S CHINESE, UNCHANGED except for the mechanical strips applied by
//     .tools/parse-dialogue.py (the `说话人：` markup prefix, one wrapping pair of “…” quotes) and
//     one user-authorised spelling fix declared in `zh_fixes` inside translated-en.json
//     (那自然在再好不过 -> 那自然再好不过). Nothing else is reworded.
//
//     ENGLISH: `TextEn` is the English translation from .tools/dialogue/translated-en.json, keyed
//     npc -> slot -> line order. That file also records the Chinese each line translates, and this
//     generator fails when the two disagree, so the translation cannot silently drift from the
//     draft. `YetanniaAncientDialoguePlan.LocEntries` returns `TextEn` for `eng` and `Text` for
//     every other language (Chinese remains the fallback).
// </auto-generated>

using System.Collections.Generic;

namespace Yetannia.YetanniaCode.Ancients;

internal static class YetanniaAncientDialogueData
{
    /// <summary>One authored line. <see cref="Speaker"/> is "ancient" or "character".</summary>
    internal sealed class DraftLine
    {
        internal DraftLine(string speaker, string text, string textEn)
        {
            Speaker = speaker;
            Text = text;
            TextEn = textEn;
        }

        internal readonly string Speaker;

        /// <summary>The user's Chinese, verbatim (after the declared spelling fix).</summary>
        internal readonly string Text;

        /// <summary>The English translation of <see cref="Text"/>, from translated-en.json.</summary>
        internal readonly string TextEn;
    }

    /// <summary>One heading of the draft.</summary>
    internal sealed class DraftSection
    {
        internal DraftSection(string slot, DraftLine[] lines)
        {
            Slot = slot;
            Lines = lines;
        }

        internal readonly string Slot;
        internal readonly DraftLine[] Lines;
    }

    /// <summary>Every section the user wrote for one Ancient.</summary>
    internal sealed class DraftAncient
    {
        internal DraftAncient(string entry, DraftSection[] sections)
        {
            Entry = entry;
            Sections = sections;
        }

        /// <summary>The Ancient's model id entry, e.g. <c>"NEOW"</c>.</summary>
        internal readonly string Entry;

        internal readonly DraftSection[] Sections;
    }

    internal static readonly DraftAncient[] Ancients =
    [
'''


def cs_literal(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            raise ValueError(f"control character U+{ord(ch):04X} in {s!r}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def apply_zh_fixes(parsed, fixes, problems):
    """Apply the Chinese spelling corrections declared in translated-en.json.

    Kept as data in the translation file rather than hard-coded: the exact edit is auditable, and
    each fix is anchored to the WHOLE line so it can never land on a different sentence. The
    .docx drafts and parsed.json are never edited -- this only corrects the emitted C# data.
    Returns the number of fixes applied and the number already present upstream.
    """
    applied = 0
    already = 0
    for fix in fixes:
        npc, slot, index = fix.get("npc"), fix.get("slot"), fix.get("index")
        try:
            section = next(s for s in parsed[npc]["sections"] if s["slot"] == slot)
            line = section["lines"][index]
        except (KeyError, TypeError, StopIteration, IndexError):
            problems.append(f"zh fix target missing from the draft: {npc}/{slot}/{index}")
            continue
        if line["text"] == fix.get("to"):
            # The fix is already present upstream (e.g. the user corrected the .docx itself):
            # nothing to do, and re-running must stay clean.
            already += 1
            continue
        if line["text"] != fix.get("from"):
            problems.append(
                f"zh fix {npc}/{slot}/{index}: draft text is {line['text']!r}, "
                f"fix expects {fix.get('from')!r}")
            continue
        line["text"] = fix.get("to", "")
        applied += 1
    return applied, already


def main():
    if not os.path.exists(PARSED):
        sys.exit(f"missing {PARSED}; run .tools/parse-dialogue.py first")
    if not os.path.exists(TRANSLATED):
        sys.exit(f"missing {TRANSLATED}; it carries the English column and is authored by hand")

    # utf-8-sig: a file rewritten by Windows tooling may carry a BOM, which plain utf-8 rejects.
    with open(PARSED, encoding="utf-8-sig") as fh:
        parsed = json.load(fh)
    with open(TRANSLATED, encoding="utf-8-sig") as fh:
        translated = json.load(fh)

    problems = []
    quote_leftovers = []
    en_by_npc = translated.get("lines") or {}
    en_used = set()

    fixes_applied, fixes_already = apply_zh_fixes(parsed, translated.get("zh_fixes") or [], problems)

    body = []
    for npc, entry, model in ANCIENTS:
        data = parsed.get(npc)
        if data is None:
            problems.append(f"no parsed data for {npc}")
            continue

        by_slot = {}
        for section in data["sections"]:
            slot = section["slot"]
            if slot in by_slot:
                problems.append(f"{npc}: duplicate slot {slot}")
            by_slot[slot] = section

        slots = [s for s in SLOT_ORDER if s in by_slot]
        if entry == "THE_ARCHITECT":
            slots = ["architect-main"] if "architect-main" in by_slot else []
            unexpected = sorted(set(by_slot) - set(slots))
        else:
            unexpected = sorted(set(by_slot) - set(SLOT_ORDER))
        if unexpected:
            problems.append(f"{npc}: unmapped slot(s) {unexpected}")
        missing = [s for s in SLOT_ORDER if s not in by_slot]
        if entry != "THE_ARCHITECT" and missing:
            problems.append(f"{npc}: slot(s) absent from the draft {missing}")

        en_slots = en_by_npc.get(npc)
        if not isinstance(en_slots, dict):
            problems.append(f"{npc}: no English translation block")
            en_slots = {}

        body.append(f'        // ---- {npc} ({model}) ----')
        body.append(f'        new DraftAncient({cs_literal(entry)},')
        body.append("        [")
        for slot in slots:
            lines = by_slot[slot]["lines"]
            en_lines = en_slots.get(slot)
            if not isinstance(en_lines, list):
                problems.append(f"{npc}/{slot}: no English translation block")
                en_lines = []
            if len(en_lines) != len(lines):
                problems.append(
                    f"{npc}/{slot}: {len(lines)} draft line(s) but {len(en_lines)} English line(s)")
            body.append(f'            new DraftSection({cs_literal(slot)},')
            body.append("            [")
            for i, ln in enumerate(lines):
                text = ln["text"]
                if not text:
                    problems.append(f"{npc}/{slot}: empty line")
                if "“" in text or "”" in text:
                    quote_leftovers.append((npc, slot, text))

                en = ""
                if i < len(en_lines):
                    item = en_lines[i]
                    en_used.add((npc, slot, i))
                    if not isinstance(item, dict) or item.get("zh") != text:
                        anchor = item.get("zh") if isinstance(item, dict) else item
                        problems.append(
                            f"{npc}/{slot}/{i}: translation is anchored to different Chinese: "
                            f"{anchor!r} != {text!r}")
                    else:
                        en = item.get("en") or ""
                        if not en.strip():
                            problems.append(f"{npc}/{slot}/{i}: empty English line")
                        elif CJK.search(en):
                            problems.append(f"{npc}/{slot}/{i}: English still contains CJK: {en!r}")
                body.append(
                    f'                new DraftLine({cs_literal(ln["speaker"])}, '
                    f"{cs_literal(text)}, {cs_literal(en)}),")
            body.append("            ]),")
        body.append("        ]),")
        body.append("")

    # Every translated line must be claimed by a draft line: an unmapped npc/slot/extra line is a
    # typo in the translation file, not something to ignore.
    unclaimed = []
    for npc, en_slots in en_by_npc.items():
        if not isinstance(en_slots, dict):
            continue
        for slot, en_lines in en_slots.items():
            if not isinstance(en_lines, list):
                continue
            for i in range(len(en_lines)):
                if (npc, slot, i) not in en_used:
                    unclaimed.append(f"{npc}/{slot}/{i}")
    if unclaimed:
        problems.append(f"English line(s) no draft line claims: {unclaimed[:8]}"
                        + (" ..." if len(unclaimed) > 8 else ""))

    body.append("    ];")
    body.append("}")

    if problems:
        print("refusing to write: the draft and the English column do not line up", file=sys.stderr)
        for p in problems:
            print("  - " + p, file=sys.stderr)
        return 1

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEADER)
        fh.write("\n".join(body))
        fh.write("\n")

    total_lines = sum(len(s["lines"]) for d in parsed.values() for s in d["sections"])
    print(f"wrote {OUT}")
    print(f"  {len(ANCIENTS)} ancient(s), {total_lines} Chinese line(s), {len(en_used)} English line(s)")
    if fixes_applied:
        print(f"  {fixes_applied} user-authorised Chinese spelling fix(es) applied")
    if fixes_already:
        print(f"  {fixes_already} declared spelling fix(es) already present in the draft")

    if quote_leftovers:
        # Not fatal: a line may legitimately contain an inner quotation. Reported so the
        # strip is auditable rather than silent.
        rp = os.path.join(HERE, "dialogue", "report.json")
        with open(rp, encoding="utf-8") as fh:
            report = json.load(fh)
        report["lines_still_containing_quotes"] = [
            {"npc": n, "slot": s, "text": t} for n, s, t in quote_leftovers]
        with open(rp, "w", encoding="utf-8", newline="\n") as fh:
            json.dump(report, fh, ensure_ascii=False, indent=2)
            fh.write("\n")
        print(f"  note: {len(quote_leftovers)} line(s) still contain a quote character "
              f"(listed in .tools/dialogue/report.json)")

    return 0


if __name__ == "__main__":
    sys.exit(main())
