#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generate Yetannia's Ancient-dialogue C# data file from .tools/dialogue/parsed.json.

Input : .tools/dialogue/parsed.json          (produced by .tools/parse-dialogue.py)
Output: Yetannia/Code/Ancients/YetanniaAncientDialogueData.g.cs

Run:  python .tools/parse-dialogue.py && python .tools/gen-ancient-dialogue.py

Why generate C# rather than ship a localization JSON:

  * The mod already localizes everything else in code (`Loc.Pick` / `ILocalizationProvider`),
    and its gameplay strings must survive a mid-session language switch -- `LocManager.SetLanguage`
    rebuilds every LocTable from disk, so anything not re-injected afterwards is wiped. Injecting
    from a static C# table on `LocManager.GetTable` is the pattern this mod already uses three
    times (KeywordLocPatch, SettingsLocPatch, ModelLocReloadPatch).
  * The dialogue keys are this mod's own namespace (`YETANNIA-TALK.*`), so the text does not have
    to be threaded through vanilla's derived-key naming at all. That is why the English column is
    absent: the user supplied Chinese only, and the same Chinese is registered for every language
    so that no raw key can ever surface. See the class comment in the generated file.

Escaping: C# string literals are emitted with `\\`, `\"` and `\n` escaped. Any line containing a
character that cannot be represented safely is reported and the script exits non-zero.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PARSED = os.path.join(HERE, "dialogue", "parsed.json")
OUT = os.path.join(ROOT, "Yetannia", "Code", "Ancients", "YetanniaAncientDialogueData.g.cs")

# docx NPC -> the Ancient model id entry the game uses for `base.Id.Entry`, i.e. what
# `AncientDialogueSet.PopulateLocKeys(ancientEntry)` receives. Measured from the vanilla
# `ancients` loc table (keys are `<ENTRY>.talk...`) and from the model classes.
#
# The vanilla class each entry belongs to is listed so the patch targets are auditable.
ANCIENTS = [
    ("涅奥", "NEOW", "MegaCrit.Sts2.Core.Models.Events.Neow"),
    ("欧洛巴斯", "OROBAS", "MegaCrit.Sts2.Core.Models.Events.Orobas"),
    ("佩尔", "PAEL", "MegaCrit.Sts2.Core.Models.Events.Pael"),
    ("瓦库", "VAKUU", "MegaCrit.Sts2.Core.Models.Events.Vakuu"),
    ("坦克斯", "TANX", "MegaCrit.Sts2.Core.Models.Events.Tanx"),
    ("特兹卡塔拉", "TEZCATARA", "MegaCrit.Sts2.Core.Models.Events.Tezcatara"),
    ("诺奴佩普", "NONUPEIPE", "MegaCrit.Sts2.Core.Models.Events.Nonupeipe"),
    ("达弗", "DARV", "MegaCrit.Sts2.Core.Models.Events.Darv"),
    ("建筑师", "THE_ARCHITECT", "(TheArchitect: has its own DialogueSet, not an AncientEventModel)"),
]

# The section slots the plan understands, in dialogue-index order. Must stay in sync with
# YetanniaAncientDialoguePlan.Slots in the hand-written C# file.
SLOT_ORDER = [
    "first",
    "first@branch1",
    "repeat1",
    "repeat2",
    "late",
    "late@branch1",
    "late@branch2",
    "generic1",
    "generic2",
]

HEADER = '''// <auto-generated>
//     Generated by .tools/gen-ancient-dialogue.py from the user's .docx drafts in
//     .tools/dialogue/ (via .tools/dialogue/parsed.json). DO NOT EDIT BY HAND.
//
//     Re-generate with:
//         python .tools/parse-dialogue.py && python .tools/gen-ancient-dialogue.py
//
//     Each DraftSection.Slot matches one heading in the user's draft:
//         generic1/generic2 -> 通用1 / 通用2
//         first            -> 初次见面           first@branch1 -> 分支1
//         repeat1          -> 重复拜访 / 重复拜访1
//         repeat2          -> 重复拜访2
//         late             -> 第三次及其以后
//         late@branch1     -> 第三次及其以后分支1
//         late@branch2     -> 第三次及其以后分支2
//         architect-main   -> the Architect's one flat, heading-less conversation
//
//     The TEXT IS THE USER'S CHINESE, UNCHANGED except for two mechanical strips applied by the
//     parser and reported in .tools/dialogue/report.json: the `说话人：` markup prefix, and one
//     wrapping pair of “…” quotes. Nothing is translated, paraphrased or reworded.
//
//     ENGLISH: the user supplied Chinese only. `Text` is registered for EVERY language (including
//     `eng`) so a raw key can never appear; the English lines are therefore the Chinese text
//     pending English copy. See YetanniaAncientDialoguePlan.
// </auto-generated>

using System.Collections.Generic;

namespace Yetannia.YetanniaCode.Ancients;

internal static class YetanniaAncientDialogueData
{
    /// <summary>One authored line. <see cref="Speaker"/> is "ancient" or "character".</summary>
    internal sealed class DraftLine
    {
        internal DraftLine(string speaker, string text)
        {
            Speaker = speaker;
            Text = text;
        }

        internal readonly string Speaker;
        internal readonly string Text;
    }

    /// <summary>One heading of the draft.</summary>
    internal sealed class DraftSection
    {
        internal DraftSection(string slot, DraftLine[] lines)
        {
            Slot = slot;
            Lines = lines;
        }

        internal readonly string Slot;
        internal readonly DraftLine[] Lines;
    }

    /// <summary>Every section the user wrote for one Ancient.</summary>
    internal sealed class DraftAncient
    {
        internal DraftAncient(string entry, DraftSection[] sections)
        {
            Entry = entry;
            Sections = sections;
        }

        /// <summary>The Ancient's model id entry, e.g. <c>"NEOW"</c>.</summary>
        internal readonly string Entry;

        internal readonly DraftSection[] Sections;
    }

    internal static readonly DraftAncient[] Ancients =
    [
'''


def cs_literal(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            raise ValueError(f"control character U+{ord(ch):04X} in {s!r}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def main():
    if not os.path.exists(PARSED):
        sys.exit(f"missing {PARSED}; run .tools/parse-dialogue.py first")

    with open(PARSED, encoding="utf-8") as fh:
        parsed = json.load(fh)

    problems = []
    quote_leftovers = []

    body = []
    for npc, entry, model in ANCIENTS:
        data = parsed.get(npc)
        if data is None:
            problems.append(f"no parsed data for {npc}")
            continue

        by_slot = {}
        for section in data["sections"]:
            slot = section["slot"]
            if slot in by_slot:
                problems.append(f"{npc}: duplicate slot {slot}")
            by_slot[slot] = section

        slots = [s for s in SLOT_ORDER if s in by_slot]
        if entry == "THE_ARCHITECT":
            slots = ["architect-main"] if "architect-main" in by_slot else []
            unexpected = sorted(set(by_slot) - set(slots))
        else:
            unexpected = sorted(set(by_slot) - set(SLOT_ORDER))
        if unexpected:
            problems.append(f"{npc}: unmapped slot(s) {unexpected}")
        missing = [s for s in SLOT_ORDER if s not in by_slot]
        if entry != "THE_ARCHITECT" and missing:
            problems.append(f"{npc}: slot(s) absent from the draft {missing}")

        body.append(f'        // ---- {npc} ({model}) ----')
        body.append(f'        new DraftAncient({cs_literal(entry)},')
        body.append("        [")
        for slot in slots:
            lines = by_slot[slot]["lines"]
            body.append(f'            new DraftSection({cs_literal(slot)},')
            body.append("            [")
            for ln in lines:
                text = ln["text"]
                if not text:
                    problems.append(f"{npc}/{slot}: empty line")
                if "“" in text or "”" in text:
                    quote_leftovers.append((npc, slot, text))
                body.append(f'                new DraftLine({cs_literal(ln["speaker"])}, {cs_literal(text)}),')
            body.append("            ]),")
        body.append("        ]),")
        body.append("")

    body.append("    ];")
    body.append("}")

    if problems:
        print("refusing to write: the draft does not match the expected structure", file=sys.stderr)
        for p in problems:
            print("  - " + p, file=sys.stderr)
        return 1

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEADER)
        fh.write("\n".join(body))
        fh.write("\n")

    total_lines = sum(len(s["lines"]) for d in parsed.values() for s in d["sections"])
    print(f"wrote {OUT}")
    print(f"  {len(ANCIENTS)} ancient(s), {total_lines} line(s)")

    if quote_leftovers:
        # Not fatal: a line may legitimately contain an inner quotation. Reported so the
        # strip is auditable rather than silent.
        rp = os.path.join(HERE, "dialogue", "report.json")
        with open(rp, encoding="utf-8") as fh:
            report = json.load(fh)
        report["lines_still_containing_quotes"] = [
            {"npc": n, "slot": s, "text": t} for n, s, t in quote_leftovers]
        with open(rp, "w", encoding="utf-8", newline="\n") as fh:
            json.dump(report, fh, ensure_ascii=False, indent=2)
            fh.write("\n")
        print(f"  note: {len(quote_leftovers)} line(s) still contain a quote character "
              f"(listed in .tools/dialogue/report.json)")

    return 0


if __name__ == "__main__":
    sys.exit(main())
