    public override PotionPoolModel PotionPool => ModelDb.PotionPool<YetanniaPotionPool>();

    // ---- art (packed into Yetannia.pck, see .tools/pckproject) ----
    //
    // CharacterSelectIcon is the portrait shown on the character select screen; it is loaded with
    // ResourceLoader.Load<CompressedTexture2D>, which is why the art has to go through Godot's
    // importer instead of being a loose .png next to the dll.
    //
    // MEASURED CONVENTION (retail pck): vanilla's select portrait is
    // images/packed/character_select/char_select_<id>.png at 132x195, an OPAQUE RGB portrait
    // (alpha is 255 everywhere), and the button draws it stretched with expand_mode 5 in an 88x130
    // masked slot. char_select_yetannia.png is 528x780 -- exactly 4x that, same 0.6769 aspect -- so
    // the portrait slot was already correct and is deliberately left as the 528x780 file.

    /// <summary>Portrait on the character select screen.</summary>
    public override string CustomCharacterSelectIconPath => ModAssets.CharUi("char_select_yetannia.png");

    /// <summary>
    /// Shown on the select screen while the character is still locked.
    ///
    /// This MUST be a different asset from the portrait above. Vanilla ships a second file,
    /// <c>char_select_&lt;id&gt;_locked.png</c> (132x195 like the portrait), which is a BLACK
    /// SILHOUETTE on a flat grey field -- measured on char_select_ironclad_locked.png, whose ctex
    /// payload is 1528 B against the portrait's 21 250 B precisely because it is a flat two-colour
    /// image. Pointing both slots at the portrait, which this class used to do, made the locked state
    /// show her artwork instead of a silhouette.
    ///
    /// The silhouette is generated by <c>.tools/build-select-bg.py</c> from the alpha channel of the
    /// rendered 88x88 cut-out icon, so the shape is the character's own silhouette.
    /// </summary>
    public override string CustomCharacterSelectLockedIconPath => ModAssets.CharUi("char_select_yetannia_locked.png");

    /// <summary>Small icon in the run info popup / top panel.</summary>
    public override string CustomIconTexturePath => ModAssets.CharUi("character_icon_yetannia.png");

    /// <summary>Icon outline, drawn on top of the map in multiplayer.</summary>
    public override string CustomIconOutlineTexturePath => ModAssets.CharUi("character_icon_yetannia_outline.png");

    // ---- scene-based models ---------------------------------------------------------------
    //
    // These slots normally point at the base game's Ironclad scenes (PlaceholderCharacterModel).
    // Pointing them at our own scenes makes the in-combat figure, the campfire and the merchant
    // Yetannia instead of the Ironclad placeholder. The scenes are tiny (a node plus a Sprite2D
    // using the same texture as the select portrait); BaseLib's node factories turn them into the
    // real NCreatureVisuals / NRestSiteCharacter / NMerchantCharacter at load time.

    /// <summary>In-combat creature model.</summary>
    public override string CustomVisualPath => ModAssets.Scene("creature_visuals/yetannia");

    /// <summary>Model shown sitting at the rest site (campfire).</summary>
    public override string CustomRestSiteAnimPath => ModAssets.Scene("rest_site/yetannia_rest_site");

    /// <summary>Model shown in shops.</summary>
    public override string CustomMerchantAnimPath => ModAssets.Scene("merchant/yetannia_merchant");

    /// <summary>Backdrop behind the character on the character select screen.</summary>
    public override string CustomCharacterSelectBg => ModAssets.Scene("char_select/char_select_bg_yetannia");

    /// <summary>
    /// The four multiplayer rock/paper/scissors hands.
    ///
    /// Same <c>PlaceholderID</c> root cause as the energy counter and the map marker below:
    /// <see cref="PlaceholderCharacterModel"/> derives all four of these from the placeholder id
    /// ("ironclad" by default), so without these overrides the multiplayer relic minigame showed the
    /// Ironclad's arm no matter what. BaseLib's four <c>Arm*TexturePath</c> patches
    /// (<c>BaseLib.Abstracts/ArmPointingTexturePath.cs</c> and its three siblings) read these
    /// properties and return early when they are non-null, which is what makes the override take
    /// effect.
    ///
    /// The art is NOT hand-drawn: it is rendered from the same decoded 3D rig as the in-combat
    /// flipbook and the character icon, by <c>.tools/hand-render.py</c>, so the hand is hers and
    /// carries the same toon shading. Canvas and framing follow the measured vanilla convention.
    /// </summary>
    /// <inheritdoc cref="CustomArmPointingTexturePath" />
    public override string CustomArmPointingTexturePath => ModAssets.Image("ui/hands/multiplayer_hand_yetannia_point.png");

    /// <summary>Fist. See <see cref="CustomArmPointingTexturePath"/>.</summary>
    public override string CustomArmRockTexturePath => ModAssets.Image("ui/hands/multiplayer_hand_yetannia_rock.png");

    /// <summary>Open palm. See <see cref="CustomArmPointingTexturePath"/>.</summary>
    public override string CustomArmPaperTexturePath => ModAssets.Image("ui/hands/multiplayer_hand_yetannia_paper.png");

    /// <summary>Index and middle extended. See <see cref="CustomArmPointingTexturePath"/>.</summary>
    public override string CustomArmScissorsTexturePath => ModAssets.Image("ui/hands/multiplayer_hand_yetannia_scissors.png");

    /// <summary>
    /// Yetannia's own in-combat energy orb.
    ///
    /// This override is load-bearing: <see cref="PlaceholderCharacterModel"/> derives the counter from
    /// <c>PlaceholderID</c> (default "ironclad"), so leaving it alone made the bottom-left energy orb the
    /// Ironclad's red one no matter what the card pool's energy colour said — the art never went through
    /// the energy-icon chain at all. Reported by the user as "the energy at the bottom left is still red".
    ///
    /// The shipped scene is the vanilla skeleton with the five layer textures hue-migrated red -> violet;
    /// the two Ironclad-only fire VFX scenes are deliberately not instantiated. See
    /// <c>scenes/energy_counter/yetannia_energy_counter.tscn</c>.
    /// </summary>
    public override string CustomEnergyCounterPath => ModAssets.Scene("energy_counter/yetannia_energy_counter");

    /// <summary>
    /// Yetannia's map marker — the emblem drawn on the act map and the run-history map.
    ///
    /// Same root cause as the energy counter above: without this override the marker came from
    /// <c>PlaceholderID</c> and was the Ironclad's. The base game ships these as standalone 49×64 PNGs
    /// (<c>images/packed/map/icons/map_marker_&lt;id&gt;.png</c>) — not as atlas slices — so replacing one
    /// is a plain asset swap.
    /// </summary>
    public override string? CustomMapMarkerPath => ModAssets.Image("ui/map_marker_yetannia.png");

    /// <summary>
    /// Yetannia's card-play trail.
    ///
    /// Same <c>PlaceholderID</c> root cause as the two above. This one needed no new art: all five vanilla
    /// trails reference the same five textures and the same shared additive material, so a character's
    /// identity lives entirely in the scene's colour slots. The shipped scene is the vanilla one with
    /// those slots hue-migrated to violet and nothing else changed.
    ///
    /// NOTE: <c>CustomCharacterSelectTransitionPath</c> is deliberately NOT overridden. The transition
    /// material's shader writes only <c>COLOR.a</c> — it never samples colour — so there is nothing to
    /// tint, and the base game already has defect and regent reuse <c>ironclad_transition.png</c> as the
    /// mask. The visible wipe colour comes from the <c>NTransition</c> ColorRect's own colour, not from
    /// this file, so overriding it would be a no-op.
    /// </summary>
    public override string CustomTrailPath => ModAssets.Scene("vfx/card_trail_yetannia");

    // ------------------------------------------------------------------ voice
    //
    // Everything below exists because of one BaseLib default. PlaceholderCharacterModel derives ALL of
    // these from `PlaceholderID`, which defaults to "ironclad" and which this class never overrode — so
    // the character was silently using the Ironclad's voice, map marker and energy counter. See the
    // notes on each override below for what was wrong and what was chosen instead.
    //
    // Voice: the game's character SFX are FMOD *events* (`event:/sfx/characters/<id>/<id>_attack`), not
    // files, and nothing in the assembly loads an extra FMOD bank from a mod folder — so a mod cannot
    // add new events, and borrowing another character's voice was only ever a stopgap.
    //
    // The four paths below therefore point at events that DO NOT EXIST. They are not meant to resolve:
    // they are sentinels that VoiceSfxPatch watches for on SfxCmd.Play, at which point it plays one of
    // our own ogg files (Chinese or Japanese, per the 语音语言 setting) instead. Two things make that
    // safe rather than clever:
    //   * the names are unique to this character, so unlike the previous "borrow necrobinder's events"
    //     approach a real Necrobinder player can never be affected;
    //   * if the patch were ever not installed, FMOD would look up a missing event — a silent no-op, not
    //     a crash and not someone else's voice.
    //
    // CharacterTransitionSfx is deliberately LEFT on necrobinder: it is a UI wipe sound rather than a
    // voice line, and there is no equivalent line in the extracted dub.

    public override string CharacterSelectSfx => VoicePack.SelectEvent;

    public override string CharacterTransitionSfx => "event:/sfx/ui/wipe_necrobinder";

    public override string CustomAttackSfx => VoicePack.AttackEvent;

    public override string CustomCastSfx => VoicePack.CastEvent;

    public override string CustomDeathSfx => VoicePack.DeathEvent;

    public override Control CustomIcon
    {
        get
        {
            var icon = NodeFactory<Control>.CreateFromResource(CustomIconTexturePath);
            icon.SetAnchorsAndOffsetsPreset(Control.LayoutPreset.FullRect);
            return icon;
        }
    }

